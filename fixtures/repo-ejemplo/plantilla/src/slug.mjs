/**
 * Convierte una cadena de texto en un slug apto para URL.
 * Plantilla base: devuelve cadena vacía para stubs o entradas no válidas.
 * La tarea task-slug implementa la lógica completa.
 */
export function slugify(text) {
  if (typeof text !== 'string' || text.length === 0) {
    return '';
  }
  return '';
}
